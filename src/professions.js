  function find(idOrName) {
    if (!idOrName) return LIBRARY[0];
    var needle = String(idOrName).trim().toLowerCase();
    for (var i = 0; i < LIBRARY.length; i++) {
      if (LIBRARY[i].id === needle || LIBRARY[i].name.toLowerCase() === needle) return LIBRARY[i];
    }
    /* Мягкое совпадение по началу названия — «фронтенд» → «Frontend-разработчик». */
    for (var j = 0; j < LIBRARY.length; j++) {
      var libName = LIBRARY[j].name.toLowerCase();
      if (libName.indexOf(needle) === 0 || needle.indexOf(libName) === 0) return LIBRARY[j];
    }
    return null;
  }

  function list() {
    return LIBRARY.map(function (p) {
      return { id: p.id, name: p.name, group: p.group };
    });
  }

  function groups() {
    var out = [];
    LIBRARY.forEach(function (p) {
      if (out.indexOf(p.group) < 0) out.push(p.group);
    });
    return out;
  }

