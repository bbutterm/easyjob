/* Распознавание текста на кадре — точка расширения.

   В прототипе распознавание не подключено: локальные библиотеки
   распознавания тянут большие модели и заметно усложняют сборку.
   Вместо этого в прототипе используется режим vision, где кадр
   читает мультимодальная модель.

   Интерфейс зафиксирован здесь, чтобы подключение распознавания
   позже не потребовало менять сессию:

     recognize(frame) -> Promise<{ ok, text, engine, error }>

   Что стоит учесть при подключении:
     — распознавание должно идти локально: кадр экрана содержит чужие
       персональные данные, отправлять его наружу лишний раз нельзя;
     — нужен режим сравнения с прошлым кадром, чтобы в модель уходил
       только изменившийся текст (переменная screen.textDelta);
     — язык интерфейса собеседования может отличаться от языка резюме. */

'use strict';

async function recognize() {
  return {
    ok: false,
    text: '',
    engine: 'none',
    error: 'Распознавание текста не подключено в прототипе. '
      + 'Используйте режим чтения «vision» или «mock».'
  };
}

function isAvailable() {
  return false;
}

module.exports = { recognize, isAvailable };
